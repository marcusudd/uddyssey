#!/usr/bin/env bash
# Sync skills/ (the single source) into the two generated skill folders:
#   template/.claude/skills/   read by Claude Code
#   template/.agents/skills/   read by Codex and Cursor
# Edit skills in skills/<name>/ only — the generated copies are overwritten
# on every run.
set -euo pipefail
cd "$(dirname "$0")"

MARKER='<!-- generated by sync.sh — edit skills/<name>/SKILL.md, not this copy -->'

for target in template/.claude/skills template/.agents/skills; do
  # Wipe generated content, keep the folder
  find "$target" -mindepth 1 -maxdepth 1 ! -name .gitkeep -exec rm -rf {} +

  for src in skills/*/; do
    [ -d "$src" ] || continue
    name=$(basename "$src")
    cp -R "$src" "$target/$name"
    # Stamp the marker under the frontmatter of SKILL.md
    f="$target/$name/SKILL.md"
    if [ -f "$f" ]; then
      awk -v m="$MARKER" '
        NR==1 && $0=="---" { fm=1 }
        fm==1 && NR>1 && $0=="---" { print; print m; fm=2; next }
        { print }
      ' "$f" > "$f.tmp" && mv "$f.tmp" "$f"
    fi
  done
done

count=$(find skills -mindepth 1 -maxdepth 1 -type d 2>/dev/null | wc -l | tr -d ' ')
echo "Synced $count skill(s) to template/.claude/skills and template/.agents/skills"
